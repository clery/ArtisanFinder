- Los acuerdos usan una página de pergamino de tamaño fijo con tarjetas de objetos como las de las misiones, indicadores claros de materiales que faltan y un sello de finalización.
- Las cantidades de materiales proceden del cliente y se guardan al aceptar el acuerdo. Reabrir un acuerdo aceptado no solicita ni cambia esas cantidades; los datos no disponibles siguen siendo desconocidos.
- Los acuerdos privados requieren que ambos jugadores usen una versión compatible de ArtisanFinder. No fabrican, intercambian ni transfieren oro automáticamente.]]
